-- Hongsi: initial database structure. Apply ONCE to an empty development project.
-- This migration creates no users, imports no records, and deletes no data.
-- RLS is enabled with no client policies: app access stays closed until the
-- Firebase identity integration and reviewed authorization migration are added.
begin;

create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

create function app_private.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := statement_timestamp();
  return new;
end;
$$;
revoke all on function app_private.touch_updated_at() from public, anon, authenticated;

-- A person is stored once, even if they have both an assistant profile and app access.
-- Firebase subjects are TEXT, not Supabase Auth UUIDs. NULL means not linked yet.
create table public.staff (
  id bigint generated by default as identity primary key,
  firebase_uid text unique check (firebase_uid is null or btrim(firebase_uid) <> ''),
  full_name text not null check (btrim(full_name) <> ''),
  email text not null unique check (email = lower(btrim(email)) and email <> ''),
  phone text,
  positions text[] not null default '{}',
  duties text[] not null default '{}',
  employment_status text not null default 'active' check (employment_status in ('active', 'inactive')),
  started_on date,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Kept separate so a staff directory query need not expose bank details.
create table public.staff_private_details (
  staff_id bigint primary key references public.staff(id) on delete restrict,
  bank_account text,
  updated_at timestamptz not null default now()
);

create table public.app_access (
  staff_id bigint primary key references public.staff(id) on delete restrict,
  app_role text not null default 'assistant' check (app_role in ('assistant', 'manager', 'admin')),
  access_status text not null default 'pending' check (access_status in ('pending', 'approved', 'suspended')),
  device_id text,
  updated_at timestamptz not null default now()
);

create table public.locations (
  id bigint generated by default as identity primary key,
  name text not null unique check (btrim(name) <> ''),
  latitude double precision check (latitude between -90 and 90),
  longitude double precision check (longitude between -180 and 180),
  notes text,
  updated_at timestamptz not null default now(),
  constraint locations_coordinate_pair check ((latitude is null) = (longitude is null))
);

create table public.classes (
  id bigint generated by default as identity primary key,
  class_code text not null unique check (class_code = btrim(class_code) and class_code <> ''),
  term_label text not null check (btrim(term_label) <> ''),
  school text,
  subject text,
  location_id bigint references public.locations(id) on delete restrict,
  weekdays smallint[] not null default '{}'
    check (weekdays <@ array[0,1,2,3,4,5,6]::smallint[] and array_position(weekdays, null) is null),
  default_start_time time,
  default_end_time time,
  default_hourly_rate_krw integer check (default_hourly_rate_krw >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint classes_time_pair check ((default_start_time is null) = (default_end_time is null)),
  constraint classes_name_present check (coalesce(btrim(school), '') <> '' or coalesce(btrim(subject), '') <> '')
);
create index classes_term_idx on public.classes(term_label, id);
create index classes_location_idx on public.classes(location_id);

-- Default staff for a class. Copy explicitly when making a session's roster.
create table public.class_staff (
  class_id bigint not null references public.classes(id) on delete restrict,
  staff_id bigint not null references public.staff(id) on delete restrict,
  primary key (class_id, staff_id)
);
create index class_staff_staff_idx on public.class_staff(staff_id, class_id);

create table public.class_sessions (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete restrict,
  session_number integer not null check (session_number > 0),
  session_date date not null,
  start_time time,
  end_time time,
  location_id bigint references public.locations(id) on delete restrict,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (class_id, session_number),
  -- Allows composite FKs to prove that a session belongs to the specified class.
  unique (class_id, id),
  constraint sessions_time_pair check ((start_time is null) = (end_time is null))
);
create index class_sessions_date_idx on public.class_sessions(session_date, id);
create index class_sessions_location_idx on public.class_sessions(location_id);

create table public.session_staff (
  session_id bigint not null references public.class_sessions(id) on delete restrict,
  staff_id bigint not null references public.staff(id) on delete restrict,
  primary key (session_id, staff_id)
);
create index session_staff_staff_idx on public.session_staff(staff_id, session_id);

create table public.students (
  id bigint generated by default as identity primary key,
  -- Existing student ID is global across classes; preserve leading zeroes.
  student_code text not null unique check (student_code = btrim(student_code) and student_code <> ''),
  full_name text not null check (btrim(full_name) <> ''),
  student_phone text,
  parent_phone text,
  email text,
  -- Shared across all classes. Having two phone numbers does not imply consent
  -- to send to both; only an explicit preference change selects both by default.
  default_message_recipients text not null default 'parent'
    check (default_message_recipients in ('parent', 'both')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.enrollments (
  class_id bigint not null references public.classes(id) on delete restrict,
  student_id bigint not null references public.students(id) on delete restrict,
  joined_on date,
  ended_on date,
  primary key (class_id, student_id),
  check (ended_on is null or joined_on is null or ended_on >= joined_on)
);
create index enrollments_student_idx on public.enrollments(student_id, class_id);

