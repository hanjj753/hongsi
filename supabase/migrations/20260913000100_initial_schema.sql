-- Explicit table list: never change access for unrelated tables in an existing project.
do $$
declare
  target_table text;
  sequence_name text;
begin
  foreach target_table in array array[
    'staff', 'staff_private_details', 'app_access', 'locations', 'classes',
    'class_staff', 'class_sessions', 'session_staff', 'students', 'enrollments',
    'student_session_records', 'session_homeworks', 'student_homework_results',
    'session_tests', 'student_test_results', 'work_logs', 'messages',
    'sending_devices', 'message_deliveries', 'inquiries'
  ] loop
    execute format('alter table public.%I enable row level security', target_table);
    execute format('revoke all on table public.%I from public, anon, authenticated', target_table);
    if exists (select 1 from information_schema.columns c
      where c.table_schema = 'public' and c.table_name = target_table and c.column_name = 'updated_at') then
      execute format('create trigger touch_updated_at before update on public.%I '
        'for each row execute function app_private.touch_updated_at()', target_table);
    end if;
    if exists (select 1 from information_schema.columns c
      where c.table_schema = 'public' and c.table_name = target_table and c.column_name = 'id') then
      sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
      if sequence_name is not null then
        execute format('revoke all on sequence %s from public, anon, authenticated', sequence_name);
      end if;
    end if;
  end loop;
end;
$$;

