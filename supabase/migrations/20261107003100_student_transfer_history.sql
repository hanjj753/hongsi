-- Additive only: preserve existing enrollments and record future transfers atomically.
begin;
set local lock_timeout = '3s';
set local statement_timeout = '30s';

create table public.student_transfers (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(id) on delete cascade,
  source_class_id bigint not null references public.classes(id) on delete cascade,
  target_class_id bigint not null references public.classes(id) on delete cascade,
  source_joined_on date,
  effective_on date not null,
  created_at timestamptz not null default now(),
  check (source_class_id <> target_class_id),
  unique (student_id, source_class_id, target_class_id, effective_on)
);
create index student_transfers_source_idx on public.student_transfers(source_class_id, student_id);
create index student_transfers_target_idx on public.student_transfers(target_class_id, student_id);
create index student_transfers_student_idx on public.student_transfers(student_id, effective_on, id);
alter table public.student_transfers enable row level security;
revoke all on public.student_transfers from public, anon, authenticated;
grant select on public.student_transfers to authenticated;
create policy approved_read on public.student_transfers for select to authenticated
  using ((select app_private.current_app_role()) is not null);

-- Only information still present in enrollments can be recovered for older transfers.
insert into public.student_transfers(student_id, source_class_id, target_class_id, source_joined_on, effective_on)
select student_id, class_id, transferred_to_class_id, joined_on, coalesce(status_changed_on, ended_on + 1)
from public.enrollments where enrollment_status = 'transferred';

create function app_private.record_student_transfer()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.enrollment_status = 'transferred' and (
    old.enrollment_status is distinct from new.enrollment_status
    or old.transferred_to_class_id is distinct from new.transferred_to_class_id
    or old.status_changed_on is distinct from new.status_changed_on
  ) then
    insert into public.student_transfers(student_id, source_class_id, target_class_id, source_joined_on, effective_on)
    values (new.student_id, new.class_id, new.transferred_to_class_id, new.joined_on,
      coalesce(new.status_changed_on, new.ended_on + 1))
    on conflict (student_id, source_class_id, target_class_id, effective_on) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function app_private.record_student_transfer() from public, anon, authenticated;
create trigger record_student_transfer after update on public.enrollments
for each row execute function app_private.record_student_transfer();

commit;
