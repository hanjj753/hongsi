-- One delivery per actual recipient. Storing two phones never implicitly sends two SMS.
-- 'submitted' means accepted for sending; it does NOT claim handset delivery.
create table public.message_deliveries (
  message_id bigint not null references public.messages(id) on delete cascade,
  recipient_type text not null check (recipient_type in ('student', 'parent')),
  status text not null default 'pending'
    check (status in ('pending', 'sending', 'submitted', 'failed', 'cancelled', 'unknown', 'legacy_sent')),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  last_attempt_at timestamptz,
  submitted_at timestamptz,
  last_error text,
  sending_device_id uuid references public.sending_devices(id) on delete restrict,
  updated_at timestamptz not null default now(),
  primary key (message_id, recipient_type),
  check (status <> 'submitted' or submitted_at is not null)
);
create index message_deliveries_pending_idx on public.message_deliveries(message_id)
  where status = 'pending';
create index message_deliveries_device_idx on public.message_deliveries(sending_device_id)
  where sending_device_id is not null;

-- Reject a delivery with no corresponding phone. This also makes imported missing
-- contact cases visible instead of silently enqueueing an unsendable message.
create function app_private.check_delivery_phone()
returns trigger language plpgsql set search_path = '' as $$
declare recipient_phone text;
begin
  select case new.recipient_type
    when 'student' then m.student_phone_snapshot else m.parent_phone_snapshot end
    into recipient_phone from public.messages m where m.id = new.message_id;
  if recipient_phone is null or btrim(recipient_phone) = '' then
    raise exception 'A delivery requires its recipient phone snapshot' using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function app_private.check_delivery_phone() from public, anon, authenticated;
create trigger message_deliveries_phone before insert or update of message_id, recipient_type
  on public.message_deliveries for each row execute function app_private.check_delivery_phone();

-- Snapshot contents never change after creation; correction means cancel + new message.
create function app_private.prevent_message_edit()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new is distinct from old then
    raise exception 'Message snapshots are immutable; cancel and create a replacement' using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function app_private.prevent_message_edit() from public, anon, authenticated;
create trigger messages_immutable before update on public.messages
  for each row execute function app_private.prevent_message_edit();

